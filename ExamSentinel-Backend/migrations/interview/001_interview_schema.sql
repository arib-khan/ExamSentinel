-- ExamSentinel :: Interview module schema (PostgreSQL / Supabase)
-- Safe to re-run. Does not touch any existing Exam table.
-- Run in Supabase > SQL Editor.

CREATE OR REPLACE FUNCTION interview_set_updated_at() RETURNS trigger AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END $$ LANGUAGE plpgsql;

-- ---------- lookup tables (add a row = add a new type, no code/schema change) ----------
CREATE TABLE IF NOT EXISTS interview_types (
  type_code  VARCHAR(30) PRIMARY KEY,
  label      VARCHAR(80) NOT NULL,
  is_active  SMALLINT NOT NULL DEFAULT 1
);
INSERT INTO interview_types (type_code, label) VALUES
  ('technical','Technical Interview'), ('hr','HR Interview'), ('general','General Interview')
ON CONFLICT DO NOTHING;
