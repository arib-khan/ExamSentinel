CREATE TABLE IF NOT EXISTS interview_question_types (
  type_code          VARCHAR(30) PRIMARY KEY,
  label              VARCHAR(80) NOT NULL,
  auto_gradable      SMALLINT NOT NULL DEFAULT 0,   -- 1 = system can score it (MCQ)
  requires_options   SMALLINT NOT NULL DEFAULT 0,
  is_active          SMALLINT NOT NULL DEFAULT 1
);
INSERT INTO interview_question_types (type_code, label, auto_gradable, requires_options) VALUES
  ('mcq','Multiple Choice',1,1), ('short_answer','Short Answer',0,0), ('subjective','Subjective',0,0),
  ('technical','Technical',0,0), ('coding','Coding',0,0), ('hr','HR',0,0)
ON CONFLICT DO NOTHING;

-- ---------- interviews ----------
CREATE TABLE IF NOT EXISTS interviews (
  interview_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title                    VARCHAR(200) NOT NULL,
  description              TEXT,
  instructions             TEXT,
  interview_type           VARCHAR(30) NOT NULL DEFAULT 'general' REFERENCES interview_types(type_code),
  status                   VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  duration_minutes         INTEGER NOT NULL CHECK (duration_minutes BETWEEN 1 AND 600),
  scheduled_start          TIMESTAMPTZ,
  scheduled_end            TIMESTAMPTZ,
  passing_percentage       NUMERIC(5,2) CHECK (passing_percentage BETWEEN 0 AND 100),
  auto_submit_on_expiry    SMALLINT NOT NULL DEFAULT 1,
  show_result_to_candidate SMALLINT NOT NULL DEFAULT 0,
  proctoring_enabled       SMALLINT NOT NULL DEFAULT 0,
  created_by               VARCHAR(100),
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (scheduled_end IS NULL OR scheduled_start IS NULL OR scheduled_end > scheduled_start)
);
CREATE INDEX IF NOT EXISTS idx_interviews_status ON interviews(status);
CREATE INDEX IF NOT EXISTS idx_interviews_type   ON interviews(interview_type);

-- ---------- questions (independent of the exam `questions` table) ----------
CREATE TABLE IF NOT EXISTS interview_questions (
  question_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  interview_id    BIGINT NOT NULL REFERENCES interviews(interview_id) ON DELETE CASCADE,
  question        TEXT NOT NULL,
  question_type   VARCHAR(30) NOT NULL REFERENCES interview_question_types(type_code),
  category        VARCHAR(100),
  difficulty      VARCHAR(10) NOT NULL DEFAULT 'medium' CHECK (difficulty IN ('easy','medium','hard')),
  marks           NUMERIC(6,2) NOT NULL DEFAULT 1 CHECK (marks >= 0),
  expected_answer TEXT,
  options         JSONB,                 -- MCQ: [{"key":"A","text":"..."}]
  correct_option  VARCHAR(10),           -- MCQ only
  display_order   INTEGER NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_iq_interview_order ON interview_questions(interview_id, display_order);

-- ---------- assignment ----------
CREATE TABLE IF NOT EXISTS interview_candidates (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  interview_id  BIGINT NOT NULL REFERENCES interviews(interview_id) ON DELETE CASCADE,
  candidate_id  VARCHAR(100) NOT NULL,      -- = "user".user_id (existing auth users with the Candidate role)
  max_attempts  INTEGER NOT NULL DEFAULT 1 CHECK (max_attempts >= 1),
  assigned_by   VARCHAR(100),
  assigned_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (interview_id, candidate_id)
);
CREATE INDEX IF NOT EXISTS idx_ic_candidate ON interview_candidates(candidate_id);

-- ---------- attempts ----------
CREATE TABLE IF NOT EXISTS interview_attempts (
  attempt_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  interview_id      BIGINT NOT NULL REFERENCES interviews(interview_id) ON DELETE CASCADE,
  candidate_id      VARCHAR(100) NOT NULL,
  attempt_no        INTEGER NOT NULL DEFAULT 1,
  start_time        TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at        TIMESTAMPTZ NOT NULL,                 -- server-side deadline (authoritative)
  end_time          TIMESTAMPTZ,
  submission_time   TIMESTAMPTZ,
  status            VARCHAR(20) NOT NULL DEFAULT 'in_progress'
                    CHECK (status IN ('in_progress','submitted','auto_submitted','expired')),
  evaluation_status VARCHAR(30) NOT NULL DEFAULT 'not_submitted'
                    CHECK (evaluation_status IN ('not_submitted','pending_manual_review','auto_evaluated','evaluated')),
  score             NUMERIC(8,2),
  total_marks       NUMERIC(8,2),
  percentage        NUMERIC(5,2),                          -- NULL until evaluation is complete
  duration_seconds  INTEGER,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ia_interview  ON interview_attempts(interview_id);
CREATE INDEX IF NOT EXISTS idx_ia_candidate  ON interview_attempts(candidate_id);
CREATE INDEX IF NOT EXISTS idx_ia_open       ON interview_attempts(status, expires_at) WHERE status = 'in_progress';
-- at most ONE running attempt per candidate+interview (race-proof)
CREATE UNIQUE INDEX IF NOT EXISTS uq_ia_one_open ON interview_attempts(interview_id, candidate_id) WHERE status = 'in_progress';

-- ---------- answers ----------
CREATE TABLE IF NOT EXISTS interview_answers (
  answer_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id        BIGINT NOT NULL REFERENCES interview_attempts(attempt_id) ON DELETE CASCADE,
  question_id       BIGINT NOT NULL REFERENCES interview_questions(question_id) ON DELETE CASCADE,
  answer_text       TEXT,
  selected_option   VARCHAR(10),
  answered_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  marks_awarded     NUMERIC(6,2),          -- NULL = not graded yet
  is_auto_graded    SMALLINT NOT NULL DEFAULT 0,
  evaluator_comment TEXT,
  UNIQUE (attempt_id, question_id)
);

-- ---------- evaluations ----------
CREATE TABLE IF NOT EXISTS interview_evaluations (
  evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id    BIGINT NOT NULL UNIQUE REFERENCES interview_attempts(attempt_id) ON DELETE CASCADE,
  evaluator_id  VARCHAR(100),                -- NULL when fully auto-evaluated
  status        VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','in_progress','finalized')),
  total_score   NUMERIC(8,2),
  comments      TEXT,
  finalized_at  TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- proctoring / security events ----------
CREATE TABLE IF NOT EXISTS interview_events (
  event_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id  BIGINT NOT NULL REFERENCES interview_attempts(attempt_id) ON DELETE CASCADE,
  event_type  VARCHAR(50) NOT NULL,
  severity    VARCHAR(10) NOT NULL DEFAULT 'info' CHECK (severity IN ('info','warning','critical')),
  details     JSONB,
  source      VARCHAR(20) NOT NULL DEFAULT 'web',   -- web | mobile
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ie_attempt ON interview_events(attempt_id, occurred_at);

-- ---------- updated_at triggers ----------
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['interviews','interview_questions','interview_attempts','interview_evaluations'] LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = t || '_updated_at') THEN
      EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION interview_set_updated_at()', t || '_updated_at', t);
    END IF;
  END LOOP;
END $$;

-- ---------- optional FKs to the existing "user" table (only if user_id is unique there) ----------
DO $$ DECLARE t text; BEGIN
  IF EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid = '"user"'::regclass AND i.indisunique
             AND i.indnatts = 1 AND (SELECT attname FROM pg_attribute WHERE attrelid = i.indrelid AND attnum = i.indkey[0]) = 'user_id') THEN
    FOR t IN SELECT unnest(ARRAY['interview_candidates.candidate_id','interview_attempts.candidate_id']) LOOP
      BEGIN
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES "user"(user_id)',
          split_part(t,'.',1), 'fk_' || replace(t,'.','_') || '_user', split_part(t,'.',2));
      EXCEPTION WHEN duplicate_object THEN NULL; END;
    END LOOP;
  ELSE
    RAISE NOTICE 'user.user_id has no unique index; skipped FKs to "user"';
  END IF;
END $$;

