-- ExamSentinel :: LIVE VIDEO INTERVIEW schema (PostgreSQL / Supabase)
-- New tables only (live_*). Safe to re-run. Does not touch any Exam table or the old Q&A interview tables.

CREATE OR REPLACE FUNCTION live_interview_set_updated_at() RETURNS trigger AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END $$ LANGUAGE plpgsql;

-- ---------- the scheduled meeting ----------
CREATE TABLE IF NOT EXISTS live_interviews (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meeting_code        VARCHAR(12)  NOT NULL UNIQUE,          -- human friendly, shown to HR/candidate (e.g. K7QM-4TXP)
  room_name           VARCHAR(80)  NOT NULL UNIQUE,          -- LiveKit room (random, never shown to the candidate UI)
  title               VARCHAR(200) NOT NULL,
  description         TEXT,
  host_id             VARCHAR(100) NOT NULL,                 -- HR interviewer = "user".user_id
  candidate_id        VARCHAR(100) NOT NULL,                 -- candidate        = "user".user_id (role Candidate)
  candidate_name      VARCHAR(150) NOT NULL,
  candidate_email     VARCHAR(200),
  candidate_phone     VARCHAR(40),
  scheduled_start     TIMESTAMPTZ  NOT NULL,
  duration_minutes    INTEGER      NOT NULL CHECK (duration_minutes BETWEEN 5 AND 480),
  scheduled_end       TIMESTAMPTZ  NOT NULL,
  status              VARCHAR(12)  NOT NULL DEFAULT 'scheduled'
                      CHECK (status IN ('scheduled','live','ended','cancelled','expired')),
  monitoring_required SMALLINT     NOT NULL DEFAULT 1,       -- 1 = workspace camera expected
  started_at          TIMESTAMPTZ,
  ended_at            TIMESTAMPTZ,
  end_reason          VARCHAR(40),
  cancelled_at        TIMESTAMPTZ,
  invite_sent_at      TIMESTAMPTZ,
  created_by          VARCHAR(100),
  created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CHECK (scheduled_end > scheduled_start)
);
CREATE INDEX IF NOT EXISTS idx_li_candidate ON live_interviews(candidate_id, scheduled_start);
CREATE INDEX IF NOT EXISTS idx_li_host      ON live_interviews(host_id, scheduled_start);
CREATE INDEX IF NOT EXISTS idx_li_status    ON live_interviews(status, scheduled_start);

-- ---------- one row per access token handed out (who joined, from which device role, with what consent) ----------
CREATE TABLE IF NOT EXISTS live_interview_sessions (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  live_interview_id BIGINT NOT NULL REFERENCES live_interviews(id) ON DELETE CASCADE,
  user_id           VARCHAR(100) NOT NULL,
  role              VARCHAR(10)  NOT NULL CHECK (role IN ('host','candidate','monitor')),
  identity          VARCHAR(160) NOT NULL,                   -- LiveKit participant identity
  consent_at        TIMESTAMPTZ,                             -- candidate/monitor must accept the disclosure
  token_issued_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  token_expires_at  TIMESTAMPTZ  NOT NULL,
  joined_at         TIMESTAMPTZ,
  left_at           TIMESTAMPTZ,
  last_seen_at      TIMESTAMPTZ,
  state             VARCHAR(14)  NOT NULL DEFAULT 'issued'
                    CHECK (state IN ('issued','connected','reconnecting','disconnected')),
  client            VARCHAR(10)  NOT NULL DEFAULT 'web'      -- web | mobile
);
CREATE INDEX IF NOT EXISTS idx_lis_interview ON live_interview_sessions(live_interview_id, role, id DESC);

-- ---------- audit trail ----------
CREATE TABLE IF NOT EXISTS live_interview_events (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  live_interview_id BIGINT NOT NULL REFERENCES live_interviews(id) ON DELETE CASCADE,
  user_id           VARCHAR(100),
  role              VARCHAR(10),
  event_type        VARCHAR(40) NOT NULL,
  details           JSONB,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_lie_interview ON live_interview_events(live_interview_id, created_at);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'live_interviews_updated_at') THEN
    CREATE TRIGGER live_interviews_updated_at BEFORE UPDATE ON live_interviews
      FOR EACH ROW EXECUTE FUNCTION live_interview_set_updated_at();
  END IF;
END $$;

-- optional FKs to the existing "user" table (only when user_id is unique there)
DO $$ DECLARE t text; BEGIN
  IF EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid = '"user"'::regclass AND i.indisunique
             AND i.indnatts = 1 AND (SELECT attname FROM pg_attribute WHERE attrelid = i.indrelid AND attnum = i.indkey[0]) = 'user_id') THEN
    FOR t IN SELECT unnest(ARRAY['live_interviews.host_id','live_interviews.candidate_id']) LOOP
      BEGIN
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES "user"(user_id)',
          split_part(t,'.',1), 'fk_' || replace(t,'.','_') || '_user', split_part(t,'.',2));
      EXCEPTION WHEN duplicate_object THEN NULL; END;
    END LOOP;
  ELSE
    RAISE NOTICE 'user.user_id has no unique index; skipped FKs to "user"';
  END IF;
END $$;

-- keep the tables off Supabase's public REST API (the backend connects as the postgres role and is unaffected)
ALTER TABLE live_interviews         ENABLE ROW LEVEL SECURITY;
ALTER TABLE live_interview_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE live_interview_events   ENABLE ROW LEVEL SECURITY;
