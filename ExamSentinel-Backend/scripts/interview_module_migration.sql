-- =====================================================================
-- ExamSentinel :: Interview Module Migration (PostgreSQL / Supabase)
-- =====================================================================
-- Creates the dedicated interview_* tables inside the SAME existing
-- Supabase/PostgreSQL database. No existing exam table is modified,
-- and no exam data is touched.
--
-- Run with:  node scripts/run-interview-migration.js
-- (idempotent - safe to run multiple times)
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. interviews
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interviews (
  iv_id integer GENERATED BY DEFAULT AS IDENTITY,
  iv_inst_id integer,
  iv_title varchar(150) NOT NULL,
  iv_type varchar(40) NOT NULL DEFAULT 'GENERAL',
  iv_description text,
  iv_instructions text,
  iv_duration_minutes integer NOT NULL DEFAULT 30,
  iv_total_marks integer DEFAULT 0,
  iv_status varchar(20) NOT NULL DEFAULT 'DRAFT',
  iv_schedule_start timestamp,
  iv_schedule_end timestamp,
  iv_created_by varchar(80),
  iv_created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  iv_updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (iv_id),
  CONSTRAINT fk_interviews_inst FOREIGN KEY (iv_inst_id) REFERENCES institute (inst_id)
);
CREATE INDEX IF NOT EXISTS interviews_iv_inst_id_idx ON interviews (iv_inst_id);
CREATE INDEX IF NOT EXISTS interviews_iv_status_idx ON interviews (iv_status);

-- ---------------------------------------------------------------------
-- 2. interview_questions
--    Independent from the exam `questions` table.
--    iq_question_type is a free varchar so new types (AI, BEHAVIORAL,
--    COMMUNICATION ...) can be added later without a schema change.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interview_questions (
  iq_id integer GENERATED BY DEFAULT AS IDENTITY,
  iq_interview_id integer NOT NULL,
  iq_question text NOT NULL,
  iq_question_type varchar(30) NOT NULL DEFAULT 'SUBJECTIVE',
  iq_category varchar(100),
  iq_difficulty varchar(10) DEFAULT 'MEDIUM',
  iq_marks integer NOT NULL DEFAULT 1,
  iq_expected_answer text,
  iq_options jsonb,
  iq_correct_option varchar(10),
  iq_order integer NOT NULL DEFAULT 1,
  iq_created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  iq_updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (iq_id),
  CONSTRAINT fk_iq_interview FOREIGN KEY (iq_interview_id) REFERENCES interviews (iv_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS interview_questions_iq_interview_id_idx ON interview_questions (iq_interview_id);

-- ---------------------------------------------------------------------
-- 3. interview_candidates  (interview <-> student assignment)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interview_candidates (
  ic_id integer GENERATED BY DEFAULT AS IDENTITY,
  ic_interview_id integer NOT NULL,
  ic_student_id integer NOT NULL,
  ic_status varchar(20) NOT NULL DEFAULT 'ASSIGNED',
  ic_assigned_by varchar(80),
  ic_created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ic_id),
  CONSTRAINT uq_ic_interview_student UNIQUE (ic_interview_id, ic_student_id),
  CONSTRAINT fk_ic_interview FOREIGN KEY (ic_interview_id) REFERENCES interviews (iv_id) ON DELETE CASCADE,
  CONSTRAINT fk_ic_student FOREIGN KEY (ic_student_id) REFERENCES students (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS interview_candidates_ic_student_id_idx ON interview_candidates (ic_student_id);

-- ---------------------------------------------------------------------
-- 4. interview_attempts
--    ia_deadline is computed on the SERVER at start time
--    (start + duration). The backend is the single source of truth
--    for whether an attempt is still valid - never the client timer.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interview_attempts (
  ia_id integer GENERATED BY DEFAULT AS IDENTITY,
  ia_interview_id integer NOT NULL,
  ia_student_id integer NOT NULL,
  ia_start_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ia_end_time timestamp,
  ia_deadline timestamp,
  ia_status varchar(20) NOT NULL DEFAULT 'IN_PROGRESS',
  ia_score numeric(8,2),
  ia_percentage numeric(6,2),
  ia_submission_time timestamp,
  ia_duration_seconds integer,
  ia_created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ia_updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ia_id),
  CONSTRAINT fk_ia_interview FOREIGN KEY (ia_interview_id) REFERENCES interviews (iv_id) ON DELETE CASCADE,
  CONSTRAINT fk_ia_student FOREIGN KEY (ia_student_id) REFERENCES students (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS interview_attempts_ia_interview_id_idx ON interview_attempts (ia_interview_id);
CREATE INDEX IF NOT EXISTS interview_attempts_ia_student_id_idx ON interview_attempts (ia_student_id);

-- ---------------------------------------------------------------------
-- 5. interview_answers  (one row per question per attempt)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interview_answers (
  ians_id integer GENERATED BY DEFAULT AS IDENTITY,
  ians_attempt_id integer NOT NULL,
  ians_question_id integer NOT NULL,
  ians_selected_option varchar(10),
  ians_answer_text text,
  ians_time_spent_seconds integer DEFAULT 0,
  ians_marks_awarded numeric(8,2),
  ians_is_auto_evaluated smallint DEFAULT 0,
  ians_evaluator_comment text,
  ians_created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ians_updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ians_id),
  CONSTRAINT uq_ians_attempt_question UNIQUE (ians_attempt_id, ians_question_id),
  CONSTRAINT fk_ians_attempt FOREIGN KEY (ians_attempt_id) REFERENCES interview_attempts (ia_id) ON DELETE CASCADE,
  CONSTRAINT fk_ians_question FOREIGN KEY (ians_question_id) REFERENCES interview_questions (iq_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS interview_answers_ians_attempt_id_idx ON interview_answers (ians_attempt_id);

-- ---------------------------------------------------------------------
-- 6. interview_evaluations
--    Created as PENDING when an attempt is submitted; an authorized
--    evaluator finalizes it. No score is ever invented - manual
--    review questions stay unscored until evaluated.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interview_evaluations (
  ie_id integer GENERATED BY DEFAULT AS IDENTITY,
  ie_attempt_id integer NOT NULL,
  ie_evaluator_id varchar(80),
  ie_status varchar(20) NOT NULL DEFAULT 'PENDING',
  ie_total_marks_awarded numeric(8,2),
  ie_percentage numeric(6,2),
  ie_remarks text,
  ie_evaluated_at timestamp,
  ie_created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ie_updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ie_id),
  CONSTRAINT uq_ie_attempt UNIQUE (ie_attempt_id),
  CONSTRAINT fk_ie_attempt FOREIGN KEY (ie_attempt_id) REFERENCES interview_attempts (ia_id) ON DELETE CASCADE,
  CONSTRAINT fk_ie_evaluator FOREIGN KEY (ie_evaluator_id) REFERENCES "user" (user_id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- 7. interview_events  (interview-specific security/proctoring log,
--    kept separate from exam_activity_log and linked to the attempt)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS interview_events (
  iev_id integer GENERATED BY DEFAULT AS IDENTITY,
  iev_attempt_id integer,
  iev_interview_id integer,
  iev_student_id integer,
  iev_event_type varchar(100) NOT NULL,
  iev_event_details text,
  iev_ip_address varchar(45),
  iev_created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (iev_id),
  CONSTRAINT fk_iev_attempt FOREIGN KEY (iev_attempt_id) REFERENCES interview_attempts (ia_id) ON DELETE CASCADE,
  CONSTRAINT fk_iev_interview FOREIGN KEY (iev_interview_id) REFERENCES interviews (iv_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS interview_events_iev_attempt_id_idx ON interview_events (iev_attempt_id);
CREATE INDEX IF NOT EXISTS interview_events_iev_student_id_idx ON interview_events (iev_student_id);

-- =====================================================================
-- Permission wiring: register the "interviews" system object and grant
-- it to the EXISTING roles through the EXISTING object_user_role_perm
-- table, so the standard sidebar/route permission system keeps working.
--   Admin(1)             : full control
--   Client(2)            : manage + evaluate for own institute
--   Class Invigilator(3) : read + evaluate
-- =====================================================================
INSERT INTO system_objects (sys_object_name, sys_object_display_name)
SELECT 'interviews', 'Interviews'
WHERE NOT EXISTS (SELECT 1 FROM system_objects WHERE sys_object_name = 'interviews');

INSERT INTO object_user_role_perm
  (perm_sys_object_id, perm_user_role_id, create_perm, read_perm, update_perm, delete_perm, execute_perm)
SELECT so.sys_object_id, 1, 'Y', 'Y', 'Y', 'Y', 'Y'
FROM system_objects so
WHERE so.sys_object_name = 'interviews'
ON CONFLICT DO NOTHING;

INSERT INTO object_user_role_perm
  (perm_sys_object_id, perm_user_role_id, create_perm, read_perm, update_perm, delete_perm, execute_perm)
SELECT so.sys_object_id, 2, 'Y', 'Y', 'Y', 'N', 'Y'
FROM system_objects so
WHERE so.sys_object_name = 'interviews'
ON CONFLICT DO NOTHING;

INSERT INTO object_user_role_perm
  (perm_sys_object_id, perm_user_role_id, create_perm, read_perm, update_perm, delete_perm, execute_perm)
SELECT so.sys_object_id, 3, 'N', 'Y', 'N', 'N', 'Y'
FROM system_objects so
WHERE so.sys_object_name = 'interviews'
ON CONFLICT DO NOTHING;
